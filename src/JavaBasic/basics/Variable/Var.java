package JavaBasic.basics.Variable;

public class Var {

    /*
     * Topic: Java Variables
     *
     * This program demonstrates different types of variables in Java.
     * Variables are used to store data that can be reused and modified
     * during program execution.
     *
     *
     */


    public static void main(String[] args) {

        // Integer type variable
        int age = 22;

        // Floating-point variable
        float percentage = 85.5f;

        // Double type variable (more precision)
        double salary = 55000.75;

        // Character variable
        char grade = 'A';

        // Boolean variable (true or false)
        boolean isDeveloper = true;

        // String (Non-primitive data type)
        String name = "Shreekant";

        // Printing all variable values
        System.out.println("Name: " + name);
        System.out.println("Age: " + age);
        System.out.println("Percentage: " + percentage);
        System.out.println("Salary: " + salary);
        System.out.println("Grade: " + grade);
        System.out.println("Is Developer: " + isDeveloper);
    }


}
