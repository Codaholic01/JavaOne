package JavaBasic.basics.Primitvedatatypes;

public class Primitive {
    public static void main(String[] args) {

        /*
         * Topic: Primitive Data Types in Java
         *
         * This program demonstrates all 8 primitive data types:
         * byte, short, int, long, float, double, char, boolean
         *
         *
         */

        // 1. byte (1 byte)
        byte age = 25;
        System.out.println("Byte value: " + age);

        // 2. short (2 bytes)
        short year = 2025;
        System.out.println("Short value: " + year);

        // 3. int (4 bytes)
        int salary = 50000;
        System.out.println("Int value: " + salary);

        // 4. long (8 bytes)
        long population = 7800000000L;
        System.out.println("Long value: " + population);

        // 5. float (4 bytes)
        float percentage = 85.5f;
        System.out.println("Float value: " + percentage);

        // 6. double (8 bytes)
        double pi = 3.14159265359;
        System.out.println("Double value: " + pi);

        // 7. char (2 bytes)
        char grade = 'A';
        System.out.println("Char value: " + grade);

        // 8. boolean (1 bit)
        boolean isJavaFun = true;
        System.out.println("Boolean value: " + isJavaFun);
    }
}


